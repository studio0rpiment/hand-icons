"""Build the distributable library from the traced icons:
  lib/hand-icons.svg      sprite (symbol per icon × variant × direction)
  lib/hand-icons.css      sizing/colour helpers
  lib/hand-icons.json     manifest
  lib/react/              typed React component + name union
  lib/README.md
Run after vectorize.py."""
import json, os, re, shutil
from icons import FILL, NUMBER, DIRECTIONS, KINDS, KIND

import pathlib
REPO = pathlib.Path(__file__).resolve().parent.parent
SRC = str(REPO / "build" / "icons")
LIB = str(REPO / "build" / "lib")
VIEW, C, STROKE = 1024, 512, 6
shutil.rmtree(LIB, ignore_errors=True)
os.makedirs(f"{LIB}/react", exist_ok=True)

index = json.load(open(f"{SRC}/index.json"))

def path_d(kind, mode, stem):
    s = open(f"{SRC}/{kind}/svg/{mode}/{stem}.svg").read()
    d = re.search(r' d="([^"]+)"', s).group(1)
    # 1 decimal → integer coords; at 1024 units that's sub-pixel at any display size
    return re.sub(r"-?\d+\.\d", lambda m: str(int(round(float(m.group(0))))), d)

TF = {"r45": f"rotate(45 {C} {C})", "r90": f"rotate(90 {C} {C})", "r135": f"rotate(135 {C} {C})",
      "r180": f"rotate(180 {C} {C})", "r270": f"rotate(270 {C} {C})",
      "mh": f"translate({VIEW} 0) scale(-1 1)", "mv": f"translate(0 {VIEW}) scale(1 -1)",
      "mhv": f"translate({VIEW} {VIEW}) scale(-1 -1)"}

defs, symbols, manifest = [], [], []
for e in index:
    name, stem, kind = e["name"], e["file"], e["kind"]
    ink = path_d(kind, "outline", stem)
    defs.append(f'<path id="hi-p-{name}" d="{ink}"/>')
    if e["solid"]:
        defs.append(f'<path id="hi-p-{name}-solid" d="{path_d(kind, "filled", stem)}"/>')
    fill_ref = f"hi-p-{name}-solid" if e["solid"] else f"hi-p-{name}"
    ids = {}
    for d in e["directions"]:
        suffix = f"-{d}" if d else ""
        tf = f' transform="{TF[d]}"' if d else ""
        line_id, fill_id = f"hi-{name}-line{suffix}", f"hi-{name}-fill{suffix}"
        symbols.append(f'<symbol id="{line_id}" viewBox="0 0 {VIEW} {VIEW}">'
                       f'<use href="#hi-p-{name}" fill="none" stroke="currentColor" stroke-width="{STROKE}" '
                       f'stroke-linejoin="round" stroke-linecap="round"{tf}/></symbol>')
        symbols.append(f'<symbol id="{fill_id}" viewBox="0 0 {VIEW} {VIEW}">'
                       f'<use href="#{fill_ref}" fill="currentColor" fill-rule="evenodd"{tf}/></symbol>')
        ids[d or "base"] = {"line": line_id, "fill": fill_id}
    manifest.append({"number": e["number"], "name": name, "kind": kind, "solid": e["solid"],
                     "directions": [d or "base" for d in e["directions"]], "symbols": ids})

sprite = ('<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" '
          'style="position:absolute;width:0;height:0;overflow:hidden" aria-hidden="true">'
          f'<defs>{"".join(defs)}</defs>{"".join(symbols)}</svg>')
open(f"{LIB}/hand-icons.svg", "w").write(sprite)
json.dump({"viewBox": VIEW, "stroke": STROKE, "kinds": list(KINDS), "icons": manifest},
          open(f"{LIB}/hand-icons.json", "w"), indent=1)

open(f"{LIB}/hand-icons.css", "w").write("""/* hand-icons — sizing and colour helpers for the sprite */
.hi {
  display: inline-block;
  width: 1em;
  height: 1em;
  vertical-align: -0.125em;
  color: inherit;          /* icon takes the text colour; set `color` to recolour or invert */
  flex: none;
}
.hi--sm { font-size: 1rem; }
.hi--md { font-size: 1.5rem; }
.hi--lg { font-size: 2.5rem; }
.hi--xl { font-size: 4rem; }
.hi--invert { color: #fff; }
""")

names = sorted(m["name"] for m in manifest)
dirs = sorted({d for m in manifest for d in m["directions"] if d != "base"})
open(f"{LIB}/react/icons.ts", "w").write(
    "// generated by build_lib.py — do not edit\n"
    f"export const ICON_NAMES = {json.dumps(names)} as const;\n"
    "export type IconName = (typeof ICON_NAMES)[number];\n"
    f"export type IconDirection = \"base\" | {' | '.join(json.dumps(d) for d in dirs)};\n"
    "export type IconVariant = \"line\" | \"fill\";\n"
    f"export const ICON_KINDS = {json.dumps(list(KINDS))} as const;\n"
    "export type IconKind = (typeof ICON_KINDS)[number];\n"
    "/** directions available per icon (\"base\" is always present) */\n"
    f"export const ICON_DIRECTIONS: Record<IconName, readonly IconDirection[]> = "
    f"{json.dumps({m['name']: m['directions'] for m in manifest}, indent=1)};\n"
    f"export const ICON_KIND: Record<IconName, IconKind> = {json.dumps({m['name']: m['kind'] for m in manifest}, indent=1)};\n")

open(f"{LIB}/react/Icon.tsx", "w").write('''import type { SVGProps } from "react";
import type { IconDirection, IconName, IconVariant } from "./icons";

export interface IconProps extends Omit<SVGProps<SVGSVGElement>, "name"> {
  name: IconName;
  /** "line" = hollow trace of the ink, "fill" = solid (closed shapes filled). Default "line". */
  variant?: IconVariant;
  /** rotation / mirror sibling; "base" is as drawn. Default "base". */
  direction?: IconDirection;
  /** size in rem (sets font-size; the icon is 1em square). Default 1.5. */
  size?: number;
  /** accessible label; omitted = decorative (aria-hidden) */
  label?: string;
  /** path to the sprite file when it isn't inlined in the document, e.g. "/assets/hand-icons.svg" */
  sprite?: string;
}

/** Hand-drawn icon rendered from the sprite. Colour follows CSS `color`. */
export function Icon({ name, variant = "line", direction = "base", size = 1.5, label, sprite = "", className, style, ...rest }: IconProps) {
  const id = `hi-${name}-${variant}${direction === "base" ? "" : `-${direction}`}`;
  return (
    <svg
      className={["hi", className].filter(Boolean).join(" ")}
      style={{ fontSize: `${size}rem`, ...style }}
      role={label ? "img" : undefined}
      aria-label={label}
      aria-hidden={label ? undefined : true}
      {...rest}
    >
      <use href={`${sprite}#${id}`} />
    </svg>
  );
}
''')
open(f"{LIB}/react/index.ts", "w").write('export { Icon } from "./Icon";\nexport type { IconProps } from "./Icon";\nexport * from "./icons";\n')

kinds_md = "\n".join(f"- **{k}** — " + ", ".join(f"{NUMBER[n]:02d} {n}" for n in ns) for k, ns in KINDS.items())
open(f"{LIB}/README.md", "w").write(f"""# hand-icons

{len(manifest)} hand-drawn icons as one SVG sprite, with line and fill variants and rotated / mirrored
siblings. Everything is `currentColor`, so icons take the text colour and invert with `color: #fff`.

## Files

- `hand-icons.svg` — the sprite. Inline it once at the top of `<body>`, or reference it by URL.
- `hand-icons.css` — `.hi` sizing helpers (icons are 1em square, sized in rem).
- `hand-icons.json` — manifest: every icon, its kind, variants and directions, and symbol ids.
- `react/` — `<Icon>` component (TypeScript) with a typed name union.
- `catalog.html` — browsable catalog with copyable snippets.

## Symbol ids

`hi-<name>-<variant>[-<direction>]`

- variant: `line` (hollow trace of the ink) or `fill` (solid; closed shapes are filled)
- direction: omit for as-drawn, or `r45` `r90` `r135` `r180` `r270` (clockwise), `mh` `mv` `mhv` (mirrored)

Examples: `hi-arrow-bar-fill`, `hi-arrow-bar-fill-r90`, `hi-spiral-tight-line-mh`.

## Plain HTML

```html
<link rel="stylesheet" href="hand-icons.css">
<!-- inline the sprite once -->
<svg ...>…contents of hand-icons.svg…</svg>

<svg class="hi hi--lg"><use href="#hi-arrow-bar-fill-r90"/></svg>
<!-- or, with the sprite as a separate file on the same origin -->
<svg class="hi" style="color:#fff"><use href="/assets/hand-icons.svg#hi-blob-fill-r45"/></svg>
```

## WordPress / Themify

Upload `hand-icons.svg` to the theme (or `wp-content/uploads`) and either inline it with
`echo file_get_contents(...)` in `header.php` / a hook, or point `<use href>` at its URL as above.
Enqueue `hand-icons.css`, then use the `<svg class="hi">` snippet in any HTML module.

## React

```tsx
import {{ Icon }} from "./react";
<Icon name="arrow-bar" variant="fill" direction="r90" size={{2}} label="next" />
```

`name` is a typed union, so a typo fails to compile. `ICON_DIRECTIONS[name]` lists valid directions.

## Kinds

{kinds_md}

## Regenerating

`prep.py` → `split.py` → `vectorize.py` → `build_lib.py`. Add a new icon by appending a crop box to
`ICONS` in `icons.py` (its number is its position, so append, never insert) and tagging it in `KINDS`,
and optionally `FILL` / `DIRECTIONS`.
""")
print("sprite", os.path.getsize(f"{LIB}/hand-icons.svg") // 1024, "KB;", len(symbols), "symbols")
